TEST(ReadWav, ValidSilenceCorrectSampleCount) {
    // silence.wav: mono, 16000 Hz, 16-bit, 0.25 s → 4000 samples
    AudioData audio = read_wav(fixtures_dir() + "silence.wav");
    EXPECT_EQ(audio.samples.size(), 4000u);
    EXPECT_EQ(audio.sample_rate, 16000);
    EXPECT_EQ(audio.channels, 1);
    EXPECT_EQ(audio.bits_per_sample, 16);
}

TEST(ReadWav, Sine44kHzCorrectSampleRate) {
    // sine_440hz.wav: mono, 44100 Hz, 16-bit, 0.25 s → 11025 samples
    AudioData audio = read_wav(fixtures_dir() + "sine_440hz.wav");
    EXPECT_EQ(audio.sample_rate, 44100);
    EXPECT_EQ(audio.samples.size(), 11025u);
    EXPECT_EQ(audio.channels, 1);
}

TEST(ReadWav, StereoChannelCountIsTwo) {
    // stereo.wav: stereo, 44100 Hz, 16-bit, 0.25 s
    //   → 11025 frames × 2 channels = 22050 interleaved samples
    AudioData audio = read_wav(fixtures_dir() + "stereo.wav");
    EXPECT_EQ(audio.channels, 2);
    EXPECT_EQ(audio.sample_rate, 44100);
    EXPECT_EQ(audio.samples.size(), 22050u);
}

