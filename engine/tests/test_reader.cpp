// test_reader.cpp — Unit tests for audio/reader.h
//
// Coverage:
//   read_wav()
//     ValidSilenceCorrectSampleCount   — 16 kHz mono → 4000 samples
//     Sine44kHzCorrectSampleRate       — sample_rate == 44100
//     StereoChannelCountIsTwo          — channels == 2, 22050 total samples
//     NonExistentFileThrows            — missing path → runtime_error
