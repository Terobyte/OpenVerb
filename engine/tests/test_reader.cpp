// ===========================================================================
// Path helpers
// ===========================================================================

// Derive the fixtures directory from the source file's own absolute path.
// CMake on macOS passes absolute source paths to the compiler, so __FILE__
// is guaranteed to be absolute in our build environment.
static std::string fixtures_dir() {
    std::string p = __FILE__;            // …/engine/tests/test_reader.cpp
    auto sep = p.find_last_of("/\\");
    return (sep != std::string::npos ? p.substr(0, sep + 1) : std::string("./"))
           + "fixtures/";
}

// ===========================================================================
// TempFile — RAII temp-file written from a raw byte buffer
// ===========================================================================

class TempFile {
public:
    explicit TempFile(const std::vector<uint8_t>& data) {
        char tmpl[] = "/tmp/openverb_test_reader_XXXXXX";
        int fd = mkstemp(tmpl);
        if (fd < 0)
            throw std::runtime_error("mkstemp failed");
        path_ = tmpl;
        ::write(fd, data.data(), static_cast<ssize_t>(data.size()));
        ::close(fd);
    }
    ~TempFile() { if (!path_.empty()) ::unlink(path_.c_str()); }

    const std::string& path() const { return path_; }

private:
    std::string path_;
};

// ===========================================================================
// Synthetic WAV builder
// ===========================================================================

// Build a minimal RIFF/WAVE PCM file in memory.
//
// Parameters:
//   fmt_code        — audio format code (1 = PCM; 7 = μ-law; 2 = ADPCM; …)
//   channels        — number of channels
//   sample_rate     — samples per second per channel
//   bits_per_sample — bit depth (16 for our fixtures)
//   samples         — interleaved PCM samples (int16 LE)
//   insert_list     — if true, insert a minimal LIST chunk between fmt and data
//   extra_fmt_bytes — extra zero bytes appended to the fmt payload (used to
//                     create odd-sized fmt chunks to exercise RIFF pad handling)
//
// The returned buffer is a byte-accurate RIFF/WAVE file.
static std::vector<uint8_t> make_wav_bytes(
    uint16_t fmt_code,
    uint16_t channels,
    uint32_t sample_rate,
    uint16_t bits_per_sample,
    const std::vector<int16_t>& samples,
    bool insert_list = false,
    uint32_t extra_fmt_bytes = 0)
{
    std::vector<uint8_t> out;

    auto w16 = [&](uint16_t v) {
        out.push_back(static_cast<uint8_t>(v & 0xFF));
        out.push_back(static_cast<uint8_t>((v >> 8) & 0xFF));
    };
    auto w32 = [&](uint32_t v) {
        out.push_back(static_cast<uint8_t>(v & 0xFF));
        out.push_back(static_cast<uint8_t>((v >> 8)  & 0xFF));
        out.push_back(static_cast<uint8_t>((v >> 16) & 0xFF));
        out.push_back(static_cast<uint8_t>((v >> 24) & 0xFF));
    };
    auto w4 = [&](const char* cc) {
        out.push_back(static_cast<uint8_t>(cc[0]));
        out.push_back(static_cast<uint8_t>(cc[1]));
        out.push_back(static_cast<uint8_t>(cc[2]));
        out.push_back(static_cast<uint8_t>(cc[3]));
    };

    uint32_t bps_bytes   = bits_per_sample / 8u;
    uint32_t data_size   = static_cast<uint32_t>(samples.size()) * bps_bytes;
    uint32_t byte_rate   = sample_rate * channels * bps_bytes;
    uint16_t block_align = static_cast<uint16_t>(channels * bps_bytes);

    // fmt chunk payload = 16 standard bytes + any extra bytes for testing
    uint32_t fmt_payload = 16u + extra_fmt_bytes;
    // RIFF spec: chunk payloads are padded to an even byte boundary
    uint32_t fmt_pad     = fmt_payload & 1u;  // 1 if odd, 0 if even

    // A minimal LIST chunk: "LIST" header (8) + "INFO" type (4) = 12 bytes total.
    // chunk_size = 4 (just the list-type field, no sub-chunks).
    constexpr uint32_t LIST_CHUNK_SIZE  = 4u;   // content size
    constexpr uint32_t LIST_CHUNK_TOTAL = 8u + LIST_CHUNK_SIZE;

    // RIFF content = "WAVE" (4) + fmt chunk (8+payload+pad) + optional LIST (12) + data chunk
    uint32_t riff_content =
          4u                                               // "WAVE"
        + 8u + fmt_payload + fmt_pad                      // fmt chunk (hdr + payload + pad)
        + (insert_list ? LIST_CHUNK_TOTAL : 0u)           // LIST chunk
        + 8u + data_size;                                 // data chunk

    // ── RIFF descriptor ──────────────────────────────────────────────────────
    w4("RIFF");
    w32(riff_content);
    w4("WAVE");

    // ── fmt chunk ────────────────────────────────────────────────────────────
    w4("fmt ");
    w32(fmt_payload);     // chunk payload size
    w16(fmt_code);
    w16(channels);
    w32(sample_rate);
    w32(byte_rate);
    w16(block_align);
    w16(bits_per_sample);
    // extra bytes (zeros) — used to produce odd-sized fmt chunks in tests
    for (uint32_t i = 0; i < extra_fmt_bytes; ++i)
        out.push_back(0);
    // RIFF alignment pad byte (written only when payload is odd-sized)
    if (fmt_pad)
        out.push_back(0);

    // ── optional LIST chunk (between fmt and data) ────────────────────────────
    if (insert_list) {
        w4("LIST");
        w32(LIST_CHUNK_SIZE);  // payload = just the list-type word
        w4("INFO");            // list type
    }

    // ── data chunk ───────────────────────────────────────────────────────────
    w4("data");
    w32(data_size);
    for (int16_t s : samples) {
        out.push_back(static_cast<uint8_t>(s & 0xFF));
        out.push_back(static_cast<uint8_t>((s >> 8) & 0xFF));
    }

    return out;
}

