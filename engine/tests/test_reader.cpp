TEST(ReadPcm, ReadsRawPcmWithAssumedMetadata) {
    // Write 200 raw int16_t samples (no WAV header) to a temp file and verify
    // that read_pcm() fills in the hardcoded 16 kHz / mono / 16-bit contract.
    constexpr std::size_t N = 200;
    std::vector<uint8_t> raw(N * sizeof(int16_t), 0);
    // Write sample index as value so we can verify round-trip.
    for (std::size_t i = 0; i < N; ++i) {
        int16_t v = static_cast<int16_t>(i);
        raw[i * 2]     = static_cast<uint8_t>(v & 0xFF);
        raw[i * 2 + 1] = static_cast<uint8_t>((v >> 8) & 0xFF);
    }

    TempFile tmp(raw);
    AudioData audio = read_pcm(tmp.path());

    EXPECT_EQ(audio.samples.size(), N);
    EXPECT_EQ(audio.sample_rate, 16000);
    EXPECT_EQ(audio.channels, 1);
    EXPECT_EQ(audio.bits_per_sample, 16);
    EXPECT_EQ(audio.samples[0],   0);
    EXPECT_EQ(audio.samples[199], 199);
}

TEST(ReadPcm, NonExistentFileThrows) {
    EXPECT_THROW(
        read_pcm("/no/such/openverb_ghost.pcm"),
        std::runtime_error);
}
