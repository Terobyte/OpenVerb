TEST(ReadWav, NonExistentFileThrows) {
    EXPECT_THROW(
        read_wav("/no/such/path/openverb_ghost_file.wav"),
        std::runtime_error);
}

TEST(ReadWav, TruncatedWavThrows) {
    // Build a valid 100-sample WAV, then truncate the buffer to just 44 bytes
    // (the complete RIFF/fmt/data headers but zero sample bytes).
    // The data chunk header declares 200 bytes of payload that aren't there,
    // so must_read() will fail with "unexpected end of file".
    std::vector<int16_t> samples(100, 0);
    auto data = make_wav_bytes(1, 1, 16000, 16, samples);

    // 44 bytes = 8(RIFF hdr) + 4(WAVE) + 8+16(fmt chunk) + 8(data hdr)
    data.resize(44);

    TempFile tmp(data);
    EXPECT_THROW(read_wav(tmp.path()), std::runtime_error);
}

TEST(ReadWav, ListChunkBeforeDataSkippedGracefully) {
    // A WAV with: RIFF → fmt → LIST → data
    // The reader must skip the LIST chunk and still decode correctly.
    std::vector<int16_t> samples = {10, 20, 30, 40, 50, 60, 70, 80};
    auto data = make_wav_bytes(1, 1, 16000, 16, samples, /*insert_list=*/true);

    TempFile tmp(data);
    AudioData audio = read_wav(tmp.path());

    EXPECT_EQ(audio.samples.size(), 8u);
    EXPECT_EQ(audio.sample_rate, 16000);
    EXPECT_EQ(audio.channels, 1);
    // Verify sample values survive the round-trip
    EXPECT_EQ(audio.samples[0], 10);
    EXPECT_EQ(audio.samples[7], 80);
}

TEST(ReadWav, UnsupportedFormatThrowsWithMessage) {
    // Format code 7 = μ-law (G.711); not PCM.  The reader must throw with the
    // exact message "unsupported WAV format: only PCM (format 1) supported".
    auto data = make_wav_bytes(/*fmt_code=*/7, 1, 8000, 16, {});

    TempFile tmp(data);

    // 1. It must throw std::runtime_error.
    EXPECT_THROW(read_wav(tmp.path()), std::runtime_error);

    // 2. The error message must be exact.
    try {
        read_wav(tmp.path());
        FAIL() << "Expected std::runtime_error to be thrown";
    } catch (const std::runtime_error& e) {
        EXPECT_STREQ(e.what(),
                     "unsupported WAV format: only PCM (format 1) supported");
    }
}

TEST(ReadWav, Non16BitPcmThrows) {
    // An 8-bit PCM WAV (format code 1, bits_per_sample 8) is valid RIFF/WAVE
    // but read_wav() must reject it because decoding into int16_t would require
    // either a 2× over-read (bogus EOF) or an 8→16 conversion we don't do.
    // Empty samples: data_size=0 keeps the WAV header self-consistent for 8-bit.
    auto data = make_wav_bytes(/*fmt_code=*/1, 1, 16000, /*bps=*/8, {});

    TempFile tmp(data);
    EXPECT_THROW(read_wav(tmp.path()), std::runtime_error);

    try {
        read_wav(tmp.path());
        FAIL() << "Expected std::runtime_error to be thrown";
    } catch (const std::runtime_error& e) {
        EXPECT_STREQ(e.what(),
                     "unsupported WAV bit depth: only 16-bit PCM is supported");
    }
}

TEST(ReadWav, OddSizedFmtChunkHandled) {
    // A fmt chunk with payload size 17 (odd) must be followed by a silent RIFF
    // pad byte.  The reader must consume the pad so the next chunk header is
    // aligned; if it doesn't, it will mis-read the 'data' fourCC and fail.
    //
    // We pass extra_fmt_bytes=1 → fmt chunk_size = 17 (odd) → 1 pad byte in file.
    // After the fix the reader skips (17-16) + (17&1) = 1+1 = 2 bytes and then
    // finds the data chunk correctly.
    std::vector<int16_t> samples = {1, 2, 3, 4};
    auto data = make_wav_bytes(/*fmt_code=*/1, 1, 16000, 16, samples,
                               /*insert_list=*/false, /*extra_fmt_bytes=*/1);

    TempFile tmp(data);
    AudioData audio = read_wav(tmp.path());

    EXPECT_EQ(audio.samples.size(), 4u);
    EXPECT_EQ(audio.sample_rate,    16000);
    EXPECT_EQ(audio.channels,       1);
    EXPECT_EQ(audio.samples[0],     1);
    EXPECT_EQ(audio.samples[3],     4);
}

